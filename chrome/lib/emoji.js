  // The emoji whose keywords contain every word of the query, in picker order.
  // Returns null for an empty query, meaning "show everything".
  function search(query) {
    const words = String(query || "")
      .toLowerCase()
      .split(/\s+/)
      .filter(Boolean);
    if (!words.length) return null;
    const found = [];
    for (const group of GROUPS) {
      for (const [emoji, keywords] of group.items) {
        if (words.every((w) => keywords.includes(w))) found.push(emoji);
      }
    }
    return found;
  }

